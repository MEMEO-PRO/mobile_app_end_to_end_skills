#!/usr/bin/env python3
"""Add store-ready configuration and compliance files to an Expo project.

Run inside (or point at) a project created with `npx create-expo-app`. Writes:
  app.config.ts             hardened config: target API 36, fingerprint runtime, privacy manifest,
                            export compliance, blocked permissions, signed OTA updates
  eas.json                  development / preview / production build + submit profiles
  .maestro/smoke.yaml       first E2E flow (launch, sign-in screen, delete-account path)
  src/config/legal.ts       privacy / terms / deletion / support URLs used by the app
  docs/                     data-inventory.md, threat-model.md, legal.md (from templates)
  store/listing.json        listing skeleton checked by store_policy_check.py
  .github/workflows/app-gates.yml   runs the app-factory gates on every pull request

Usage:
  scaffold.py --name "My App" --package com.acme.myapp [--bundle-id com.acme.myapp]
              [--dir .] [--owner acme] [--website https://acme.com] [--force]
Exit: 0 written, 1 refused (existing files without --force), 2 bad arguments.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SKILLS = Path(__file__).resolve().parents[2]
ID_RX = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*){1,}$")


def app_config(name, slug, package, bundle, owner, website):
    return f'''import type {{ ExpoConfig }} from "expo/config";

// Generated by app-factory (app-build/scaffold.py). The stores review the native app generated
// from this file, so keep every permission justified and every usage string specific.
const config: ExpoConfig = {{
  name: "{name}",
  slug: "{slug}",
  {f'owner: "{owner}",' if owner else '// owner: "your-expo-account",'}
  version: "1.0.0",
  scheme: "{slug}",
  orientation: "portrait",
  userInterfaceStyle: "automatic",
  runtimeVersion: {{ policy: "fingerprint" }}, // OTA updates only reach binaries with the same native code
  updates: {{
    // Signed updates: generate with `npx expo-updates codesigning:generate --key-output-directory keys
    //   --certificate-output-directory certs --certificate-validity-duration-years 10 --certificate-common-name "{name}"`
    codeSigningCertificate: "./certs/certificate.pem",
    codeSigningMetadata: {{ keyid: "main", alg: "rsa-v1_5-sha256" }},
  }},
  ios: {{
    bundleIdentifier: "{bundle}",
    supportsTablet: true,
    config: {{ usesNonExemptEncryption: false }}, // true only if you add crypto beyond HTTPS / OS APIs
    infoPlist: {{
      // One specific reason per permission you actually request, e.g.:
      // NSCameraUsageDescription: "Scan receipts to add expenses",
    }},
    privacyManifests: {{
      NSPrivacyAccessedAPITypes: [
        {{ NSPrivacyAccessedAPIType: "NSPrivacyAccessedAPICategoryUserDefaults", NSPrivacyAccessedAPITypeReasons: ["CA92.1"] }},
      ],
    }},
  }},
  android: {{
    package: "{package}",
    permissions: [], // add only what a visible feature needs
    blockedPermissions: [
      "android.permission.READ_MEDIA_IMAGES", // use the Photo Picker instead
      "android.permission.READ_MEDIA_VIDEO",
      "android.permission.RECORD_AUDIO",
      "android.permission.SYSTEM_ALERT_WINDOW",
      "android.permission.READ_EXTERNAL_STORAGE",
      "android.permission.WRITE_EXTERNAL_STORAGE",
    ],
    edgeToEdgeEnabled: true,
  }},
  plugins: [
    "expo-router",
    "expo-secure-store",
    [
      "expo-build-properties",
      {{
        android: {{ targetSdkVersion: 36, compileSdkVersion: 36, minSdkVersion: 24, enableProguardInReleaseBuilds: true }},
        ios: {{ deploymentTarget: "16.0" }},
      }},
    ],
  ],
  extra: {{ website: "{website}" }},
}};

export default config;
'''


def eas_json():
    return json.dumps({
        "cli": {"version": ">= 16.0.0", "appVersionSource": "remote"},
        "build": {
            "development": {"developmentClient": True, "distribution": "internal", "channel": "development"},
            "preview": {"distribution": "internal", "channel": "preview", "android": {"buildType": "apk"}},
            "production": {"autoIncrement": True, "channel": "production"},
        },
        "submit": {
            "production": {
                "android": {"track": "internal", "releaseStatus": "draft"},
                "ios": {"ascAppId": "REPLACE_WITH_APP_STORE_CONNECT_APP_ID"},
            }
        },
    }, indent=2) + "\n"


def maestro(package):
    return f"""appId: {package}
name: Smoke test
tags:
  - smoke
---
- launchApp:
    clearState: true
- assertVisible:
    text: ".*"
# Replace with your real journey, e.g.:
# - tapOn: "Sign in"
# - inputText: "${{DEMO_EMAIL}}"
# - tapOn: "Settings"
# - assertVisible: "Delete account"
"""


def legal_ts(website):
    return f"""// Links required by both stores. Every URL must be public and live before submission.
export const legal = {{
  privacyPolicyUrl: "{website}/privacy",
  termsOfUseUrl: "{website}/terms",
  accountDeletionUrl: "{website}/delete-account", // Play: public web page to request deletion
  supportUrl: "{website}/support",
}};
"""


THREAT = """# Threat model — {name}

| Asset | Attacker wants | Entry point | Mitigation | Owner |
|---|---|---|---|---|
| Session tokens | Account takeover | Local storage, logs, backups | expo-secure-store; no tokens in logs; short-lived tokens + refresh | |
| User data on the server | Bulk data theft | API | Server-side auth on every endpoint; row-level security; rate limits | |
| OTA update channel | Push code to every user | EAS Update | Code signing (updates.codeSigningCertificate); key kept offline | |
| Deep links | Open privileged screens / phishing | URL scheme, App Links | Validate params; verified App Links / Universal Links | |
| API keys | Abuse paid APIs | Decompiled JS bundle | No secrets in the app; proxy through your server | |

Review date: ____ · Reviewed by: ____
"""

LEGAL = """# Launch countries — {name}

Fill one row per country you enable in Play Console / App Store Connect. Use skills/app-factory/references/legal-global.md.

| Country | Law | Registration / representative before launch | DPO / privacy officer | Children's consent age | Transfer mechanism / localisation | Breach deadline | Done |
|---|---|---|---|---|---|---|---|
| | | | | | | | |

Shortest breach deadline across markets: ____ · Incident owner: ____
"""


def listing(name, website):
    return json.dumps({
        "android": {"title": name, "short_description": "", "full_description": "", "privacy_url": f"{website}/privacy",
                    "account_deletion_url": f"{website}/delete-account", "contact_email": ""},
        "ios": {"name": name, "subtitle": "", "description": "", "keywords": "", "promotional_text": "",
                "privacy_url": f"{website}/privacy", "support_url": f"{website}/support"},
    }, indent=2) + "\n"


WORKFLOW = """name: app-gates
on: [pull_request]
jobs:
  gates:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with: { fetch-depth: 0 }
      - uses: actions/checkout@v4
        with: { repository: MEMEO-PRO/mobile_app_end_to_end_skills, path: .app-factory }
      - uses: actions/setup-python@v5
        with: { python-version: "3.12" }
      - run: bash .app-factory/skills/app-factory/scripts/run_gates.sh . --skills .app-factory/skills
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True)
    ap.add_argument("--package", required=True, help="Android applicationId, reverse-DNS, permanent once published")
    ap.add_argument("--bundle-id", help="iOS bundle identifier (default = --package)")
    ap.add_argument("--dir", default=".")
    ap.add_argument("--owner", default="")
    ap.add_argument("--website", default="https://example.com")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args(argv)
    bundle = a.bundle_id or a.package
    for label, val in (("--package", a.package), ("--bundle-id", bundle)):
        if not ID_RX.match(val):
            print(f"{label} '{val}' must be lowercase reverse-DNS like com.acme.myapp", file=sys.stderr)
            return 2
        if val.startswith(("com.example.", "com.yourcompany.")):
            print(f"{label} '{val}' is a placeholder the stores reject", file=sys.stderr)
            return 2
    root = Path(a.dir).resolve()
    root.mkdir(parents=True, exist_ok=True)
    slug = re.sub(r"[^a-z0-9]+", "-", a.name.lower()).strip("-")
    tpl = SKILLS / "app-factory" / "templates" / "data-inventory.md"
    files = {
        "app.config.ts": app_config(a.name, slug, a.package, bundle, a.owner, a.website.rstrip("/")),
        "eas.json": eas_json(),
        ".maestro/smoke.yaml": maestro(a.package),
        "src/config/legal.ts": legal_ts(a.website.rstrip("/")),
        "docs/data-inventory.md": tpl.read_text(encoding="utf-8").replace("<App name>", a.name) if tpl.exists() else "# Data inventory\n",
        "docs/threat-model.md": THREAT.format(name=a.name),
        "docs/legal.md": LEGAL.format(name=a.name),
        "store/listing.json": listing(a.name, a.website.rstrip("/")),
        ".github/workflows/app-gates.yml": WORKFLOW,
    }
    existing = [k for k in files if (root / k).exists()]
    if existing and not a.force:
        print("Refusing to overwrite (use --force): " + ", ".join(existing), file=sys.stderr)
        return 1
    if (root / "app.json").exists() and not a.force:
        print("Found app.json: move its settings into app.config.ts, delete app.json, then re-run (or pass --force to write anyway).", file=sys.stderr)
        return 1
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"wrote {rel}")
    print("\nNext: npx expo install expo-dev-client expo-secure-store expo-build-properties expo-updates expo-router"
          "\n      generate the OTA signing certificate (command in app.config.ts), then `eas build --profile development`.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
